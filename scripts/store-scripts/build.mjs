// Builds the Script Manager scripts ReelFlies keeps in this repo (store-scripts/) into the
// changes files W0-11's store-write helper plans from. One script so far: web-vitals field data
// to GA4 (ticket 23).
//
//   node scripts/store-scripts/build.mjs           # writes store-scripts/1895766/web-vitals.json
//   node scripts/store-scripts/build.mjs --check   # exits 1 if the committed file is stale
//
// - The Scripts API takes an inline script as `html` holding exactly one <script> tag, with
//   load_method "default" (kind script_tag). So the vendored web-vitals build and the GA4 glue
//   go in one function scope inside one tag, and add no globals.
// - The script is created disabled (W0-11 refuses anything else). Enabling it is Shaun's, in the
//   control panel, once GA4 open point (b) has its filter (research/23-analytics-and-integrations.md).
// - It goes in the footer, consent-tagged "analytics", on storefront pages only (not checkout or
//   the order confirmation), and carries no measurement id: it sends through the store's own GA4
//   tag (a global gtag, or GA4's data layer).
// - The vendored library is pinned by version and by the sha256 of the file in the repo, so an
//   edit to it, or a different release, fails the build and the tests.
//
// Nothing here talks to the store. Creating the script is W0-11's plan and apply, with the
// changes file this writes (store-scripts/README.md).

import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { isMain } from '../lib/is-main.mjs';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

// web-vitals 6.2.2 from npm (tarball integrity below), dist/web-vitals.iife.js without its last
// line, the source-map comment. 6.2.2 is the newest release that had been out two weeks on
// 2026-10-06 (6.2.3 came out on 2026-10-05). Revisitable: re-vendor as store-scripts/README.md says.
export const VENDOR = {
    name: 'web-vitals',
    version: '6.2.2',
    license: 'Apache-2.0',
    file: 'store-scripts/web-vitals/vendor/web-vitals-6.2.2.iife.js',
    sha256: 'f88532fa800e24f8e73404947b65f1b13535e5c1e08b32104cc1f0e55178aed5',
    npmIntegrity: 'sha512-oto5x6dLEgrRqfcWed+pZEUb2q6ikbFmqF54CRDhI/QGbn+qxC49b4C4OkbH+kb9C3a8shpFD3SgR9kRcs80ZQ==',
};

export const GLUE_FILE = 'store-scripts/web-vitals/rf-web-vitals.js';
export const CHANGES_FILE = 'store-scripts/1895766/web-vitals.json';
export const CHANNEL = 1895766;

// The Scripts API's limit on `html`, and this script's own share of the 150 KB gzip budget for
// every third-party script on the storefront (research.json, performance budget).
export const HTML_LIMIT = 65536;
export const GZIP_BUDGET = 4096;

export const SCRIPT = {
    name: 'ReelFlies web-vitals',
    description: 'Field data for ticket 23: LCP, INP and CLS from real visitors, sent to GA4 as events through the store\'s gtag. Built from the theme repo (store-scripts/); change it there.',
    kind: 'script_tag',
    load_method: 'default',
    location: 'footer',
    visibility: 'storefront',
    consent_category: 'analytics',
    // The writer account may be replaced after the Flip (decision 11); field data must outlive it.
    auto_uninstall: false,
};

const ABOUT = 'Ticket 23: the web-vitals field-data script for Script Manager on ReelFlies_CA (1895766), created disabled. '
    + 'Generated by scripts/store-scripts/build.mjs from store-scripts/web-vitals/; never edit it by hand. '
    + 'A lifted write (decision 4): plan and apply it with scripts/store/ (docs/store-writes.md). '
    + 'Shaun enables it in the control panel once GA4 open point (b) has its filter (research/23-analytics-and-integrations.md).';

const sha256 = text => crypto.createHash('sha256').update(text).digest('hex');

// The two sources, after checking the vendored build is the pinned one.
export function readSources(root = ROOT) {
    const vendor = fs.readFileSync(path.join(root, VENDOR.file), 'utf8');
    if (sha256(vendor) !== VENDOR.sha256) {
        throw new Error(`${VENDOR.file} doesn't match the pinned ${VENDOR.name} ${VENDOR.version} (sha256 ${VENDOR.sha256}): re-vendor it as store-scripts/README.md says`);
    }
    const glue = fs.readFileSync(path.join(root, GLUE_FILE), 'utf8');
    return { vendor, glue };
}

const withoutCommentLines = source => source.split('\n').filter(line => line.trim() && !/^\s*\/\//.test(line)).join('\n');

export function buildHtml({ vendor, glue }) {
    const body = [
        `/*! ${VENDOR.name} ${VENDOR.version} | ${VENDOR.license} | ReelFlies field data, ticket 23 */`,
        '(function () {',
        vendor.trim(),
        withoutCommentLines(glue),
        'rfWebVitals(webVitals, window);',
        '}());',
    ].join('\n');
    if (/<\/script|<!--|<script/i.test(body)) throw new Error('the script\'s text holds "<script", "</script" or "<!--", which would break the inline tag');
    return `<script>${body}\n</script>`;
}

export function buildChanges(sources) {
    return {
        _about: ABOUT,
        requests: [{
            method: 'POST',
            path: '/v3/content/scripts',
            body: {
                channel_id: CHANNEL,
                name: SCRIPT.name,
                description: SCRIPT.description,
                html: buildHtml(sources),
                kind: SCRIPT.kind,
                load_method: SCRIPT.load_method,
                location: SCRIPT.location,
                visibility: SCRIPT.visibility,
                consent_category: SCRIPT.consent_category,
                auto_uninstall: SCRIPT.auto_uninstall,
                enabled: false,
            },
        }],
    };
}

export const serialize = changes => `${JSON.stringify(changes, null, 2)}\n`;

// Null when `file` holds exactly what the sources build, else what is wrong.
export function checkChanges(file, sources) {
    let text;
    try {
        text = fs.readFileSync(file, 'utf8');
    } catch (error) {
        return `${file} can't be read (${error.code}): run node scripts/store-scripts/build.mjs`;
    }
    return text === serialize(buildChanges(sources)) ? null : `${file} is stale: run node scripts/store-scripts/build.mjs`;
}

function main(argv) {
    if (argv.length > 1 || (argv.length === 1 && argv[0] !== '--check')) {
        console.error('usage: node scripts/store-scripts/build.mjs [--check]');
        return 2;
    }
    const file = path.join(ROOT, CHANGES_FILE);
    const sources = readSources();
    if (argv[0] === '--check') {
        const problem = checkChanges(file, sources);
        if (problem) {
            console.error(problem);
            return 1;
        }
        console.log(`${CHANGES_FILE} is up to date`);
        return 0;
    }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, serialize(buildChanges(sources)));
    console.log(`wrote ${CHANGES_FILE}`);
    return 0;
}

if (isMain(import.meta.url)) process.exitCode = main(process.argv.slice(2));

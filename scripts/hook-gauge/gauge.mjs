// The hook gauge's markup (ticket 35): one builder for the theme partial and for ticket 49's
// widget sync, so both draw the same gauge.
//
// - partialSource() is templates/components/reelflies/hook-gauge.html, as generate.mjs writes
//   it: both layouts, picked by the include's gauge_layout, with the labels the include passes.
// - gaugeHtml(layout, { label, sizeLabel }) is the same markup with literal labels, for a page
//   that can't include a theme partial. render/partials/hook-gauge.test.mjs proves the two match.
// - widgetPartialSource() is widgets/_shared/hook-gauge-band.html, as generate.mjs writes it: the
//   band layout alone, the partial's own band branch, for ticket 49's home band
//   (widgets/hook-sizes). A widget template can't include a theme partial, so the widget sync
//   pastes this _shared partial into the copy it uploads (scripts/widgets/paste.mjs), and the
//   store gets the gauge drawn inline. Its labels are the widget's fields, passed as the same
//   gauge_label and gauge_size_label; render/widgets/hook-sizes.test.mjs proves the widget's
//   gauge is gaugeHtml('band') with them.
//
// Each size is an <a> to its chart row (#size-14), holding the hook as inline SVG, hidden from
// screen readers, and the size as text: the drawing needs no sprite and no script, and the text
// carries the information (spec module 22). The labels are the include's, so the strings stay in
// the includer's lang keys or widget configuration (ADR 0001), and the partial adds none.

import { fileURLToPath } from 'url';
import { CHART_SIZES, anchorId } from './sizes.mjs';
import {
    HOOK, LAYOUTS, checkCalibration, hookBox, readCalibration,
} from './geometry.mjs';

export const PARTIAL = 'components/reelflies/hook-gauge';
export const PARTIAL_FILE = fileURLToPath(new URL(`../../templates/${PARTIAL}.html`, import.meta.url));
// The band's copy for widgets, which a widget template calls as {{> _shared/hook-gauge-band …}}.
export const WIDGET_PARTIAL = '_shared/hook-gauge-band';
export const WIDGET_PARTIAL_FILE = fileURLToPath(new URL(`../../widgets/${WIDGET_PARTIAL}.html`, import.meta.url));

// Handlebars 4's escapeExpression, so a literal label renders exactly as {{label}} does.
const ESCAPES = {
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#x27;', '`': '&#x60;', '=': '&#x3D;',
};
export const escapeHtml = text => String(text).replace(/[&<>"'`=]/g, character => ESCAPES[character]);

const layoutOf = name => {
    if (!Object.hasOwn(LAYOUTS, name)) throw new Error(`unknown gauge layout "${name}" (${Object.keys(LAYOUTS).join(', ')})`);
    return LAYOUTS[name];
};

// --rf-gauge-k, then --rf-gauge-k-phone and --rf-gauge-k-narrow where the layout has them.
const scaleStyle = k => Object.entries(k).map(([name, value]) => `--rf-gauge-k${name === 'desktop' ? '' : `-${name}`}: ${value}px;`).join(' ');

function hookSvg(length, k) {
    const { width, height } = hookBox(length, k);
    const { cx, cy, r } = HOOK.eye;
    return `<svg class="rf-hook-gauge__hook" viewBox="${HOOK.viewBox}" width="${width}" height="${height}" style="--rf-hook-len: ${length};"`
        + ` fill="none" stroke="currentColor" stroke-width="${HOOK.strokeWidth}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">`
        + `<circle cx="${cx}" cy="${cy}" r="${r}" vector-effect="non-scaling-stroke"/><path d="${HOOK.path}" vector-effect="non-scaling-stroke"/></svg>`;
}

// One layout's markup. `attrs.group` is the wrapper's label attributes and `attrs.size(size)`
// each link's, already safe to put in a tag: Handlebars for the partial, escaped text for
// gaugeHtml.
function gaugeMarkup(name, lengths, attrs) {
    const layout = layoutOf(name);
    return [
        `<div class="rf-hook-gauge rf-hook-gauge--${name}"${attrs.group} style="${scaleStyle(layout.k)}">`,
        ...layout.rows.flatMap(row => [
            '    <ol class="rf-hook-gauge__row">',
            ...row.flatMap(size => [
                '        <li class="rf-hook-gauge__item">',
                `            <a class="rf-hook-gauge__link" href="${layout.href}#${anchorId(size)}"${attrs.size(size)}>`,
                `                ${hookSvg(lengths[size], layout.k.desktop)}`,
                `                <span class="rf-hook-gauge__size">${size}</span>`,
                '            </a>',
                '        </li>',
            ]),
            '    </ol>',
        ]),
        '</div>',
    ].join('\n');
}

const HANDLEBARS_ATTRS = {
    group: '{{#if gauge_label}} role="group" aria-label="{{gauge_label}}"{{/if}}',
    size: size => `{{#if gauge_size_label}} aria-label="{{gauge_size_label}} ${size}"{{/if}}`,
};

const HEADER = `{{!-- The hook size gauge, generated by scripts/hook-gauge/generate.mjs from scripts/hook-gauge/calibration.json (ticket 35).
Don't edit it by hand: change the calibration or the generator, run node scripts/hook-gauge/generate.mjs, and commit both.

Every size from ${CHART_SIZES[0]} to ${CHART_SIZES[CHART_SIZES.length - 1]} links to its row (#size-14), with the hook drawn as inline SVG to one scale.
Include it as a partial, components/reelflies/hook-gauge, with these hash arguments:
- gauge_layout: 'band' for the home band (ticket 49; CD-12), 2/0 to 20 linking to /fly-hook-size-chart/.
  Anything else, or none, draws the chart page's gauge, 6/0 to 24 linking to the rows on the same page.
- gauge_label: the drawing's short text alternative, for example (lang 'reelflies.chart.gauge_label').
  Without it the gauge isn't a labelled group.
- gauge_size_label: the word before each size in its link's name: "Size" names a link "Size 6/0".
  Without it each link is named by its visible size alone.
The style layer sizes each hook as --rf-hook-len (mm) times --rf-gauge-k (px per mm), with
--rf-gauge-k-phone and --rf-gauge-k-narrow on narrower screens (scripts/hook-gauge/geometry.mjs).
The width and height attributes draw it at the desktop scale before any style loads. --}}`;

export function partialSource(calibration = readCalibration()) {
    const { lengths } = checkCalibration(calibration);
    return [
        HEADER,
        "{{#if gauge_layout '===' 'band'}}",
        gaugeMarkup('band', lengths, HANDLEBARS_ATTRS),
        '{{else}}',
        gaugeMarkup('chart', lengths, HANDLEBARS_ATTRS),
        '{{/if}}',
        '',
    ].join('\n');
}

const WIDGET_HEADER = `{{!-- The home band's hook size gauge, generated by scripts/hook-gauge/generate.mjs from scripts/hook-gauge/calibration.json (tickets 35 and 49).
Don't edit it by hand: change the calibration or the generator, run node scripts/hook-gauge/generate.mjs, and commit what it writes.

It is the band layout of components/reelflies/hook-gauge.html, markup for markup, for a widget: a widget template can't
include a theme partial, so the widget sync pastes this one into the copy it uploads (scripts/widgets/paste.mjs).
${LAYOUTS.band.rows.map(row => `${row[0]} to ${row[row.length - 1]}`).join(', then ')}, each size linking to its row on ${LAYOUTS.band.href}, the hook drawn as inline SVG to one scale.
Call it as {{> _shared/hook-gauge-band gauge_label=… gauge_size_label=…}} with the widget's own fields:
- gauge_label: the drawing's short text alternative. Without it the gauge isn't a labelled group.
- gauge_size_label: the word before each size in its link's name: "Size" names a link "Size 2/0".
The theme's style layer sizes each hook (_chart.scss, and the band's own rules in _home-links.scss). --}}`;

export function widgetPartialSource(calibration = readCalibration()) {
    const { lengths } = checkCalibration(calibration);
    return [WIDGET_HEADER, gaugeMarkup('band', lengths, HANDLEBARS_ATTRS), ''].join('\n');
}

export function gaugeHtml(layout = 'chart', { label, sizeLabel, calibration = readCalibration() } = {}) {
    const { lengths } = checkCalibration(calibration);
    return gaugeMarkup(layout, lengths, {
        group: label ? ` role="group" aria-label="${escapeHtml(label)}"` : '',
        size: size => (sizeLabel ? ` aria-label="${escapeHtml(sizeLabel)} ${size}"` : ''),
    });
}

// The gauge generator (ticket 35): templates/components/reelflies/hook-gauge.html is written by
// scripts/hook-gauge/generate.mjs from the calibration, never by hand, and CI fails when the
// committed partial and the generator disagree.
//
//   node --test scripts/hook-gauge/generate.test.mjs

import { spawnSync } from 'child_process';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { fileURLToPath } from 'url';
import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { readCalibration } from './geometry.mjs';
import { PARTIAL_FILE, partialSource } from './gauge.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const GENERATE = path.join(HERE, 'generate.mjs');
const run = (...args) => spawnSync(process.execPath, [GENERATE, ...args], { encoding: 'utf8' });
const scratch = () => fs.mkdtempSync(path.join(os.tmpdir(), 'rf-hook-gauge-'));

describe('the generated partial', () => {
    it('is committed exactly as the generator writes it', () => {
        assert.equal(path.relative(path.join(HERE, '..', '..'), PARTIAL_FILE), path.join('templates', 'components', 'reelflies', 'hook-gauge.html'));
        assert.equal(
            fs.readFileSync(PARTIAL_FILE, 'utf8'),
            partialSource(),
            'templates/components/reelflies/hook-gauge.html differs from the generator: run node scripts/hook-gauge/generate.mjs and commit both',
        );
    });

    it('says it is generated, and how to change it, in a comment that never reaches the page', () => {
        const [first] = partialSource().split('\n');
        assert.match(first, /^\{\{!--.*generated by scripts\/hook-gauge\/generate\.mjs/i);
        assert.match(partialSource(), /--\}\}\n/);
    });

    it('is the same on every run', () => {
        assert.equal(partialSource(), partialSource());
    });

    it('follows the calibration: a changed length changes that hook\'s drawn width', () => {
        const calibration = readCalibration();
        const changed = partialSource({ ...calibration, lengths: { ...calibration.lengths, 14: 11 } });
        assert.notEqual(changed, partialSource());
        // 11 mm at the chart's 2.6 px/mm, where 10.5 mm drew 27.3 px.
        assert.match(changed, /href="#size-14"[\s\S]*?width="28\.6"/);
    });

    it('refuses to write a calibration that draws a bigger number as a bigger hook', () => {
        const calibration = readCalibration();
        assert.throws(() => partialSource({ ...calibration, lengths: { ...calibration.lengths, 24: 20 } }), /22 \(6 mm\) must be longer than 24 \(20 mm\)/);
    });
});

describe('generate.mjs', () => {
    it('--check passes on the committed partial and writes nothing', () => {
        const before = fs.statSync(PARTIAL_FILE).mtimeMs;
        const { status, stdout } = run('--check');
        assert.equal(status, 0, stdout);
        assert.match(stdout, /up to date/);
        assert.equal(fs.statSync(PARTIAL_FILE).mtimeMs, before);
    });

    it('--check fails on a partial edited by hand, and says how to fix it', () => {
        const file = path.join(scratch(), 'hook-gauge.html');
        fs.writeFileSync(file, partialSource().replace('6/0</span>', '6/0 </span>'));
        const { status, stderr } = run('--check', '--file', file);
        assert.equal(status, 1);
        assert.match(stderr, /differs from the generator/);
        assert.match(stderr, /node scripts\/hook-gauge\/generate\.mjs/);
    });

    it('writes the partial, then --check passes on it', () => {
        const file = path.join(scratch(), 'hook-gauge.html');
        const written = run('--file', file);
        assert.equal(written.status, 0, written.stderr);
        assert.equal(fs.readFileSync(file, 'utf8'), partialSource());
        assert.equal(run('--check', '--file', file).status, 0);
    });

    it('refuses an unknown argument', () => {
        const { status, stderr } = run('--force');
        assert.equal(status, 2);
        assert.match(stderr, /unknown argument --force/);
    });
});
